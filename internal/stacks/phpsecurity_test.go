// Windows security rebuilds are published with a "-1" suffix, and the plain
// filename does not exist for those releases. The downloader must try both
// spellings or a security update cannot be installed at all.
func TestPHPDownloadURLsCoversSecurityRebuilds(t *testing.T) {
	urls := phpDownloadURLs("8.5.12")
	if len(urls) == 0 {
		t.Fatal("expected download URLs")
	}
	if !strings.Contains(urls[0], "php-8.5.12-Win32-vs17-x64.zip") {
		t.Fatalf("first candidate should be the release build, got %q", urls[0])
	}

	var sawRebuild bool
	for _, u := range urls {
		if strings.Contains(u, "php-8.5.12-1-Win32-vs17-x64.zip") {
			sawRebuild = true
		}
	}
	if !sawRebuild {
		t.Fatalf("expected a php-8.5.12-1 rebuild URL, got %v", urls)
	}

	// Archive fallbacks must still be present for superseded releases.
	if !strings.Contains(strings.Join(urls, "\n"), "/archives/") {
		t.Fatalf("expected archive fallbacks, got %v", urls)
	}
}

func TestPHPVersionDefaultsToSupportedBranch(t *testing.T) {
	for _, v := range PHPInstallableVersions {
		if strings.HasPrefix(v, "8.1.") {
			t.Fatalf("8.1 is end-of-life and must not be offered: %v", PHPInstallableVersions)
		}
	}
	if !strings.HasPrefix(PHPVersion, "8.5.") {
		t.Fatalf("default managed PHP should be on the 8.5 branch, got %s", PHPVersion)
	}
}

func TestHardenPHPIniRepairsOldInstall(t *testing.T) {
	dir := t.TempDir()
	ini := filepath.Join(dir, "php.ini")
	old := strings.Join([]string{
		"; Generated by Exposely",
		"memory_limit = 512M",
		"display_errors = On",
		"cgi.fix_pathinfo = 1",
		"; expose_php = On",
	}, "\n")
	if err := os.WriteFile(ini, []byte(old), 0o644); err != nil {
		t.Fatal(err)
	}

	changed, err := HardenPHPIni(ini)
	if err != nil {
		t.Fatal(err)
	}
	if !changed {
		t.Fatal("expected the old php.ini to be changed")
	}

	got, err := os.ReadFile(ini)
	if err != nil {
		t.Fatal(err)
	}
	content := string(got)
	for _, want := range []string{
		"cgi.fix_pathinfo = 0",
		"expose_php = Off",
		"allow_url_include = Off",
		"session.cookie_httponly = 1",
		"session.use_strict_mode = 1",
		"memory_limit = 512M",
		"display_errors = On",
	} {
		if !strings.Contains(content, want) {
			t.Fatalf("hardened php.ini missing %q:\n%s", want, content)
		}
	}
	if strings.Contains(content, "cgi.fix_pathinfo = 1") {
		t.Fatalf("fix_pathinfo was not repaired:\n%s", content)
	}

	// Running it again is a no-op.
	changed, err = HardenPHPIni(ini)
	if err != nil {
		t.Fatal(err)
	}
	if changed {
		t.Fatal("second run should not rewrite the file")
	}
}

