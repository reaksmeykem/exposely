let currentLang = 'en';

export function setLang(lang: string) {
  currentLang = lang === 'km' ? 'km' : 'en';
}

export function getLang(): string {
  return currentLang;
}

export function t(key: string): string {
  return translations[currentLang]?.[key] ?? translations.en?.[key] ?? key;
}
